// Rewrites the specialist-sites directory in public/index.html from data/network.json.
// Usage: node scripts/render-network.mjs   (npm run network)
// The block between <!-- NET:START … --> and <!-- NET:END --> is replaced, the heading count and lede are refreshed,
// and the list of live domains used by the zoom chapters (#liveData) is regenerated.
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync("data/network.json", "utf8"));
const page = "public/index.html";
let html = readFileSync(page, "utf8");

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const sites = data.groups.flatMap((g) => g.sites);
const live = sites.filter((s) => s.live), soon = sites.filter((s) => !s.live);
const countOf = (g) => { const l = g.sites.filter((s) => s.live).length, b = g.sites.length - l; return [l && `${l} live`, b && `${b} in build`].filter(Boolean).join(" · "); };
const item = (s) => s.live
  ? `<li><a href="https://${s.d}/" rel="noopener" title="${esc(s.w || "")}">${s.d}</a></li>`
  : `<li class="is-soon"><span class="site site--soon" title="${esc(s.w || "In build")}">${s.d} <em>in build</em></span></li>`;

const block = `<!-- NET:START (generated by scripts/render-network.mjs from data/network.json, probed ${data.updated}) -->
    <div class="net__tools">
      <label class="net__find"><span class="sr">Find a specialist site</span><input type="search" id="netFind" placeholder="Find a site: radon, sewer, panel, furnace, demolition…" autocomplete="off" spellcheck="false"></label>
      <p class="net__count" id="netCount" aria-live="polite">${live.length} live · ${soon.length} in build · ${data.groups.length} categories</p>
    </div>
    <p class="net__legend"><span><i></i>Live site</span><span><i class="soon"></i>In build: owned, not yet published</span></p>
    <div class="net" id="netGrid">
${data.groups.map((g) => `      <div class="net__group" data-group="${g.key}"><h3>${esc(g.label)} <span>${countOf(g)}</span></h3><ul>${g.sites.map(item).join("")}</ul></div>`).join("\n")}
    </div>
    <script type="application/json" id="netData">${JSON.stringify(data.services)}</script>
    <p class="net__empty" id="netEmpty" hidden>No site matches that yet. Tell us what you need on the request form and we will route it.</p>
    `;

const a = html.indexOf("<!-- NET:START"), b = html.indexOf("<!-- NET:END -->");
if (a < 0 || b < 0) throw new Error("NET markers not found in " + page);
html = html.slice(0, a) + block + html.slice(b);
html = html.replace(/(<h2 id="network-title" data-split>)\d+( specialist sites\.)/, `$1${sites.length}$2`);
html = html.replace(/\d+ are live today and \d+ more are owned and in build\./, `${live.length} are live today and ${soon.length} more are owned and in build.`);
html = html.replace(/(<script type="application\/json" id="liveData">)[\s\S]*?(<\/script>)/, `$1${JSON.stringify(live.map((s) => s.d).sort())}$2`);
writeFileSync(page, html);
console.log(`${page}: ${sites.length} sites (${live.length} live, ${soon.length} in build) in ${data.groups.length} categories`);
